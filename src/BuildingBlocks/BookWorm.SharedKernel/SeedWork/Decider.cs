namespace BookWorm.SharedKernel.SeedWork;

public sealed record Decider<TState, TEvent>(
    Func<TState, TEvent, TState> Evolve,
    Func<TState> GetInitialState
)
{
    /// <summary>
    ///     Reconstitutes state by folding a sequence of historical events onto the initial state.
    /// </summary>
    /// <param name="events">The historical events to fold onto the initial state.</param>
    /// <returns>The reconstituted state.</returns>
    /// <exception cref="ArgumentNullException">Thrown if <paramref name="events" /> is null.</exception>
    public TState Reconstitute(IEnumerable<TEvent> events)
    {
        ArgumentNullException.ThrowIfNull(events);
        return events.Aggregate(GetInitialState(), Evolve);
    }

    /// <summary>
    ///     Executes a decision against <paramref name="currentState" /> and folds the resulting events into the next state.
    /// </summary>
    /// <typeparam name="TCommand">The command type.</typeparam>
    /// <param name="command">The command to handle.</param>
    /// <param name="currentState">The current state to handle the command against.</param>
    /// <param name="decide">The decision function producing events from the command and current state.</param>
    /// <returns>A tuple containing the next state and the events generated by handling the command.</returns>
    public (TState NextState, TEvent[] Events) Handle<TCommand>(
        TCommand command,
        TState currentState,
        Func<TCommand, TState, TEvent[]> decide
    )
    {
        ArgumentNullException.ThrowIfNull(decide);
        var events = decide(command, currentState);
        var nextState = events.Aggregate(currentState, Evolve);
        return (nextState, events);
    }

    /// <summary>
    ///     Binds a command decision function to this decider.
    /// </summary>
    /// <typeparam name="TCommand">The command type.</typeparam>
    /// <param name="decide">The decision function producing events from the command and current state.</param>
    /// <returns>A command-bound decider.</returns>
    public CommandDecider<TCommand> For<TCommand>(Func<TCommand, TState, TEvent[]> decide)
    {
        ArgumentNullException.ThrowIfNull(decide);
        return new(this, decide);
    }

    public sealed record CommandDecider<TCommand>(
        Decider<TState, TEvent> Decider,
        Func<TCommand, TState, TEvent[]> Decide
    )
    {
        public TState Reconstitute(IEnumerable<TEvent> events) => Decider.Reconstitute(events);

        public (TState NextState, TEvent[] Events) Handle(TCommand command, TState currentState) =>
            Decider.Handle(command, currentState, Decide);
    }
}
